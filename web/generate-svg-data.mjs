// Regenerates web/src/svg-data.ts from the repo's actual SVG assets.
// The SVG files are the source of truth (see README.md) — never edit svg-data.ts by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const ASSETS = {
  ndifLogoColor: 'brand/logos/ndif-logo-color.svg',
  ndifLogoBlack: 'brand/logos/ndif-logo-black.svg',
  ndifLogoWhite: 'brand/logos/ndif-logo-white.svg',
  ndifLogoWhiteOnGradient: 'brand/logos/ndif-logo-white-bg-gradient.svg',
  ndifWordmarkHorizontalColor: 'brand/logos/ndif-wordmark-horizontal-color.svg',
  ndifWordmarkHorizontalBlack: 'brand/logos/ndif-wordmark-horizontal-black.svg',
  ndifWordmarkHorizontalWhite: 'brand/logos/ndif-wordmark-horizontal-white.svg',
  ndifWordmarkStackedColor: 'brand/logos/ndif-wordmark-stacked-color.svg',
  ndifWordmarkStackedBlack: 'brand/logos/ndif-wordmark-stacked-black.svg',
  ndifWordmarkStackedWhite: 'brand/logos/ndif-wordmark-stacked-white.svg',
  nnsightLogoColor: 'projects/nnsight/nnsight-logo-color.svg',
  nnsightLogoBlack: 'projects/nnsight/nnsight-logo-black.svg',
  nnsightLogoWhite: 'projects/nnsight/nnsight-logo-white.svg',
  workbenchLogoColor: 'projects/workbench/workbench-logo-color.svg',
  workbenchLogoBlack: 'projects/workbench/workbench-logo-black.svg',
  workbenchLogoWhite: 'projects/workbench/workbench-logo-white.svg',
};

// Strip the XML prolog and leading comments — invalid inside an HTML element's innerHTML.
function clean(svg) {
  return svg.replace(/^\s*<\?xml[^>]*\?>\s*/i, '').replace(/^\s*<!--[\s\S]*?-->\s*/g, '').trim();
}

// Namespace every id per asset. Variants exported from the same source share ids
// (e.g. linearGradient503 in all three workbench files); inlined on one page,
// url(#id) resolves to the FIRST match in the document, so a monochrome variant
// would pick up the color variant's gradient.
function namespaceIds(svg, prefix) {
  return svg
    .replace(/\bid="([^"]+)"/g, (_, id) => `id="${prefix}__${id}"`)
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${prefix}__${id})`)
    .replace(/\b(xlink:href|href)="#([^"]+)"/g, (_, attr, id) => `${attr}="#${prefix}__${id}"`);
}

let out = '// GENERATED by web/generate-svg-data.mjs — do not edit. Sources: the repo\'s SVG files.\n';
for (const [name, rel] of Object.entries(ASSETS)) {
  const svg = namespaceIds(clean(readFileSync(join(root, rel), 'utf8')), name);
  out += `export const ${name} = ${JSON.stringify(svg)};\n`;
}
writeFileSync(join(root, 'web/src/svg-data.ts'), out);
console.log(`svg-data.ts: ${Object.keys(ASSETS).length} assets embedded`);
